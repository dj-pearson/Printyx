#!/usr/bin/env node
/**
 * PA-031: schema-of-record drift ratchet.
 *
 * Every table an edge function queries via `.from('x')` should be defined by a
 * versioned migration (CREATE TABLE) or a Drizzle `pgTable(...)` so the repo is
 * the source of truth and a fresh DB provisioned from migrations alone works.
 *
 * This script:
 *   - builds the set of DEFINED tables (pgTable names in shared/*.ts + CREATE
 *     TABLE names in drizzle/migrations/*.sql),
 *   - builds the set of REFERENCED tables (edge-fn `.from('literal')` calls),
 *   - reports REFERENCED-but-not-DEFINED tables ("drift"),
 *   - freezes the current drift set in a baseline and FAILS CI when a NEW drift
 *     table appears (mirrors the QUALITY-002 typecheck ratchet), and
 *   - regenerates a manifest (table -> referencing files) for remediation.
 *
 * Usage:
 *   node scripts/check-schema-drift.mjs                 # check (fails on NEW drift)
 *   node scripts/check-schema-drift.mjs --update-baseline
 */
import fs from 'fs';
import path from 'path';

const ROOT = process.cwd();
const BASELINE = path.join(ROOT, 'docs', 'schema-drift-baseline.json');
const MANIFEST = path.join(ROOT, 'docs', 'schema-drift-manifest.md');

function walk(dir, filter, out = []) {
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) return out;
  for (const e of fs.readdirSync(abs, { withFileTypes: true })) {
    const rel = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (!/node_modules|\.git/.test(rel)) walk(rel, filter, out);
    } else if (filter(e.name)) {
      out.push(rel);
    }
  }
  return out;
}

function collectDefined() {
  const defined = new Set();
  for (const f of walk('shared', (n) => n.endsWith('.ts'))) {
    const s = fs.readFileSync(path.join(ROOT, f), 'utf8');
    for (const m of s.matchAll(/pgTable\(\s*['"]([a-z0-9_]+)['"]/gi)) defined.add(m[1]);
  }
  for (const f of walk('drizzle/migrations', (n) => n.endsWith('.sql'))) {
    const s = fs.readFileSync(path.join(ROOT, f), 'utf8');
    for (const m of s.matchAll(/CREATE TABLE\s+(IF NOT EXISTS\s+)?["']?([a-z0-9_]+)["']?/gi)) {
      defined.add(m[2]);
    }
  }
  return defined;
}

function collectReferenced() {
  const referenced = new Map(); // table -> Set<file>
  for (const f of walk('supabase/functions', (n) => n.endsWith('.ts'))) {
    const s = fs.readFileSync(path.join(ROOT, f), 'utf8');
    for (const m of s.matchAll(/\.from\(\s*['"]([a-z0-9_.]+)['"]/gi)) {
      const t = m[1];
      if (t.includes('.')) continue; // skip schema-qualified (information_schema.tables)
      if (!referenced.has(t)) referenced.set(t, new Set());
      referenced.get(t).add(f.split(path.sep).join('/'));
    }
  }
  return referenced;
}

function writeManifest(driftMap) {
  const lines = [
    '# Schema-of-record drift manifest (PA-031)',
    '',
    'Auto-generated by `node scripts/check-schema-drift.mjs --update-baseline`.',
    '',
    'Edge-function tables referenced via `.from(...)` that are defined by NO',
    'migration `CREATE TABLE` and NO Drizzle `pgTable(...)`. Each needs a decision:',
    're-point to the real table, add a schema + migration, or delete the dead endpoint.',
    '',
    `Total drift tables: ${driftMap.size}`,
    '',
    '| Table | Referencing edge-fn files |',
    '| --- | --- |',
  ];
  for (const table of [...driftMap.keys()].sort()) {
    const files = [...driftMap.get(table)].sort().join('<br>');
    lines.push(`| \`${table}\` | ${files} |`);
  }
  fs.writeFileSync(MANIFEST, lines.join('\n') + '\n');
}

const defined = collectDefined();
const referenced = collectReferenced();
const driftMap = new Map();
for (const [table, files] of referenced) {
  if (!defined.has(table)) driftMap.set(table, files);
}
const driftTables = [...driftMap.keys()].sort();

const update = process.argv.includes('--update-baseline');

if (update) {
  fs.mkdirSync(path.dirname(BASELINE), { recursive: true });
  fs.writeFileSync(
    BASELINE,
    JSON.stringify(
      {
        note: 'PA-031 schema-drift ratchet baseline. Edge-fn .from() tables not defined by any migration/pgTable. Lower it (never raise) as drift is remediated; regenerate with --update-baseline.',
        count: driftTables.length,
        tables: driftTables,
      },
      null,
      2,
    ) + '\n',
  );
  writeManifest(driftMap);
  console.log(`Baseline updated: ${driftTables.length} drift tables. Manifest: ${MANIFEST}`);
  process.exit(0);
}

if (!fs.existsSync(BASELINE)) {
  console.error('No baseline found. Run: node scripts/check-schema-drift.mjs --update-baseline');
  process.exit(1);
}
const baseline = JSON.parse(fs.readFileSync(BASELINE, 'utf8'));
const known = new Set(baseline.tables || []);
const newDrift = driftTables.filter((t) => !known.has(t));

if (newDrift.length > 0) {
  console.error(
    `✗ NEW schema-drift tables referenced by edge fns but defined nowhere:\n  ${newDrift
      .map((t) => `${t} (${[...driftMap.get(t)].join(', ')})`)
      .join('\n  ')}\n` +
      'Define them (migration/pgTable), re-point to the real table, or delete the caller. ' +
      'If intentional, run --update-baseline.',
  );
  process.exit(1);
}

const resolved = [...known].filter((t) => !driftMap.has(t));
if (resolved.length > 0) {
  console.log(
    `✓ No new drift. ${resolved.length} baseline table(s) resolved — tighten with --update-baseline: ${resolved.join(', ')}`,
  );
} else {
  console.log(`✓ No new schema drift (baseline holds at ${known.size} tables).`);
}
